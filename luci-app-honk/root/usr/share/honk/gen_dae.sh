#!/bin/sh
#
# /etc/config/honk -> /etc/honk/config.dae
#
# 配置源只有 UCI，这里只做拼接，不做决策。
# honk 用 dae 语法，路由目标只能是 direct / block / 组，所以每个出口都得先成组。

# 不开 -e：这个脚本里到处是"读一个可能不存在的 UCI 字段"，
# uci get 失败会让命令替换返回非零，-e 会在第一个可选字段处掐断整个生成。
set -u

CONF="honk"
OUT="${1:-/etc/honk/config.dae}"
TMP="${OUT}.tmp.$$"
trap 'rm -f "$TMP"' EXIT HUP INT TERM
umask 077
SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"

# 测试要把整份配置指到临时目录，否则 shell 读系统 UCI、ucode 读 fixture，
# 两边看到的数据不一致，测出来的结果没有意义。command 用来绕开自身递归。
uci() { command uci ${UCI_CONFIG_DIR:+-c "$UCI_CONFIG_DIR"} "$@"; }

q() { uci -q get "$CONF.$1" 2>/dev/null || true; }
sections() { uci show "$CONF" 2>/dev/null | sed -n "s/^$CONF\.\([^.=]*\)=$1$/\1/p"; }

# 把 192.168.1.1/24 规整成 192.168.1.0/24。honk 接受带主机位的写法，
# 但规则里写网络地址语义更清楚，也避免不同版本对主机位的解释有差异。
cidr_net() {
	awk -v c="$1" 'BEGIN{
		n = split(c, p, "/")
		bits = (n > 1) ? p[2] + 0 : 32
		if (index(p[2], ".")) {
			split(p[2], mask, "."); bits = 0
			for (i = 1; i <= 4; i++) { x = mask[i] + 0; while (x > 0) { bits += x % 2; x = int(x / 2) } }
		}
		split(p[1], a, ".")
		v = a[1]*16777216 + a[2]*65536 + a[3]*256 + a[4]
		sh = 2^(32 - bits)
		v = int(v / sh) * sh
		printf "%d.%d.%d.%d/%d", int(v/16777216)%256, int(v/65536)%256, int(v/256)%256, v%256, bits
	}'
}

# honk 的字符串用单引号包；分享链接里不会有单引号，有就剔掉
sq() { printf "%s" "$1" | tr -d "\047"; }

ENABLED="$(q config.enabled)"
[ "$ENABLED" = "1" ] || exit 0

MAIN_GROUP="$(q config.main_group)"
ROUTING_MODE="$(q config.routing_mode)"
ROUTING_PORT="$(q config.routing_port)"
IPV6_MODE="$(q config.ipv6_mode)"
QUIC_MODE="$(q config.quic_mode)"
CUSTOM_ON="$(q config.custom_rules_enabled)"
CUSTOM_RULES_FILE="$(q config.custom_rules_file)"
COMMON_PORTS="20,21,22,25,53,80,110,119,123,143,389,443,465,514,563,587,636,853,873,989,990,993,995,1194,1883,3306,3389,5222,5432,5671,5672,5900,6379,6443,6514,8080,8443,8883,9418"

DATA_DIR="$(q infra.data_dir)"
LAN_IF="$(q infra.lan_interface)"
WAN_IF="$(q infra.wan_interface)"
LOG_LEVEL="$(q infra.log_level)"
BOOTSTRAP="$(q infra.bootstrap_resolver)"
# 老的单值字段：没有 dns_upstream section 时用它们兜底。
# 之前只认 section，导致 upstream{} 生成成空块、fallback: reject，全网解析不了。
CN_DNS="$(q infra.cn_dns)"
CN_DNS_CUSTOM="$(q infra.cn_dns_custom)"
REMOTE_DNS="$(q infra.remote_dns)"
REMOTE_DNS_CUSTOM="$(q infra.remote_dns_custom)"
DNS_BIND="$(q infra.bind)"
DNS_IPVER="$(q infra.ipversion_prefer)"
DNS_ECS="$(q infra.client_subnet)"
MAX_CACHE="$(q infra.max_cache_size)"
OPT_CACHE="$(q infra.optimistic_cache)"
OPT_TTL="$(q infra.optimistic_cache_ttl)"
STALE_TTL="$(q infra.optimistic_stale_reply_ttl)"
CACHE_FILE="$(q infra.cache_file)"
BLOCK_HTTPS="$(q infra.block_https_rr)"
AD_BLOCK="$(q infra.ad_block)"
NATIVE_API="$(q infra.native_api)"
API_PORT="$(q infra.native_api_port)"
[ -n "$API_PORT" ] || API_PORT="9527"
AB_FILE="$(q infra.ad_block_file)"
[ -n "$AB_FILE" ] || AB_FILE="/etc/honk/adblock.list"

NODE_CONFIG="$(ucode "$SCRIPT_DIR/generate-nodes.uc" "${UCI_CONFIG_DIR:-/etc/config}")" || exit 1
mkdir -p "$(dirname "$OUT")" || exit 1

{
  echo "# generated by /usr/share/honk/gen_dae.sh - do not edit by hand"
  echo
  echo "global {"
  [ -n "$WAN_IF" ] && echo "    wan_interface: $WAN_IF"
  # LAN 接口以 UCI 为准；配了多SSID 时自动把这些网段接口补进来，否则 honk 看不见它们
  lan_list="$LAN_IF"
  for s in $(sections ssid_route); do
    [ "$(uci -q get "$CONF.$s.enabled")" = "1" ] || continue
    iface="$(uci -q get "$CONF.$s.interface")"
    [ -n "$iface" ] || continue
    device="$(ubus call "network.interface.$iface" status 2>/dev/null | jsonfilter -e '@.l3_device')"
    [ -n "$device" ] || device="$(uci -q get "network.$iface.device")"
    [ -n "$device" ] && iface="$device"
    case ",$lan_list," in
      *",$iface,"*) ;;
      *) lan_list="${lan_list:+$lan_list, }$iface" ;;
    esac
  done
  [ -n "$lan_list" ] && echo "    lan_interface: $lan_list"
  echo "    log_level: ${LOG_LEVEL:-info}"
  echo "    data_dir: '${DATA_DIR:-/var/lib/honk}'"
  [ -n "$BOOTSTRAP" ] && echo "    bootstrap_resolver: '$(sq "$BOOTSTRAP")'"
  echo "    dial_mode: domain"
  echo "}"
  echo

  # 本地 dat 通过 init 的 DAE_LOCATION_ASSET 加载；这里只声明远程来源。
  GEOSITE_URL="${GEOSITE_URL:-https://cdn.jsdelivr.net/gh/Loyalsoldier/v2ray-rules-dat@release/geosite.dat}"
  GEOIP_URL="${GEOIP_URL:-https://github.com/Loyalsoldier/geoip/releases/latest/download/geoip.dat}"
  echo "assets {"
  echo "    geodata {"
  echo "        geosite: '$(sq "$GEOSITE_URL")'"
  echo "        geoip: '$(sq "$GEOIP_URL")'"
  echo "        route: direct"
  echo "    }"
  echo "}"
  echo

  printf '%s\n' "$NODE_CONFIG"

  # 是否有任何可用的 DNS 上游。两个角色都选"（不设置）"且没有旧 section 时，
  # 就完全不托管 DNS：既不生成 dns 块，也要把 53 直通出去。
  # 以前这种情况会生成 fallback: reject，等于把用户所有解析都掐死。
  DNS_ANY=0
  case "$CN_DNS" in none|'') ;; *) DNS_ANY=1 ;; esac
  case "$REMOTE_DNS" in none|'') ;; *) DNS_ANY=1 ;; esac
  # 只有两个字段压根不存在（空 = 尚未写过，属旧安装）才看旧 section。
  # 写成 none 是用户的明确表态，不能被旧 section 顶回来。
  if [ -z "$CN_DNS" ] && [ -z "$REMOTE_DNS" ] && [ -n "$(sections dns_upstream)" ]; then
    DNS_ANY=1
  fi

  echo "routing {"
  # 旁路由（单臂路由）拓扑下，上游和下游是同一个接口。honk 如果只按默认路由
  # 认出口，会把 br-lan 当成 WAN，连路由器自己的 SSH / LuCI / DNS 一起劫走，
  # 配完就再也连不上。先把 LAN 网段和本机 dnsmasq 放行，这两条必须在最前面。
  lan_cidr="$(uci -q get network.lan.ipaddr 2>/dev/null | head -n 1)"
  lan_ip="${lan_cidr%%/*}"
  if [ -n "$lan_cidr" ] && [ -n "$lan_ip" ]; then
    case "$lan_cidr" in
      */*) net="$(cidr_net "$lan_cidr")" ;;
      *)
        lan_mask="$(uci -q get network.lan.netmask 2>/dev/null)"
        if [ -n "$lan_mask" ]; then
          net="$(cidr_net "$lan_cidr/$lan_mask")"
        else
          net=""
        fi
        ;;
    esac
    # 只放行"局域网访问路由器本体"，不能写成 sip(<lan>) -> direct：
    # 那样连 LAN 设备去外网的流量也一起直连，代理形同虚设。
    # 目的地址限定成路由器自己的 LAN IP，入站的 SSH/LuCI 才不会被劫走。
    #
    # 必须用 direct(must)：普通 direct 只是选直连出口，DNS 仍归 honk 接管，
    # 管理连接照样会被卷进去。must 才会立即终结规则搜索、跳过 DNS 控制器。
    # 排除 53 是有意的——那一路继续走 honk 做透明 DNS。
    #
    # honk 会检查"每个本机地址是否都被放行过"，漏一个就报 self-protection
    # coverage could not be confirmed。所以这里把所有本地地址都枚举一遍，
    # 不能只写 LAN 那个 IPv4。
    _src="${net:-$lan_cidr}"
    _local="$(ip -4 -o addr show 2>/dev/null | awk '{print $4}' | cut -d/ -f1)
$(ip -6 -o addr show scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1)"
    echo "$_local" | while IFS= read -r _a; do
      [ -n "$_a" ] || continue
      case "$_a" in 127.*|::1) continue ;; esac
      echo "    sip($_src) && dip($_a) && !dport(53) -> direct(must)"
    done
  fi
  # Router 自己的 DNS 交给 dnsmasq，不要绕回 honk。
  # 注意：不能让 53 走 direct —— 明文 DNS 在国内全是投毒结果
  # （google 会解析成 Twitter / Facebook 的 IP 段），必须由 honk
  # 用加密上游解析，那才是能拿到真实地址的唯一路子。
  echo "    pname(dnsmasq) -> direct"

  target="direct"
  if [ "$MAIN_GROUP" != "nil" ] && [ -n "$MAIN_GROUP" ]; then
    target="$(sq "$MAIN_GROUP")"
  fi
  if [ "$CUSTOM_ON" = "1" ]; then
    # 自定义规则放独立文件：UCI 的 option 不能跨行，list 又会被
    # uci show 拍成一行，BusyBox sed 也没有 \n 替换。文件最省事。
    CRFILE="$CUSTOM_RULES_FILE"
    [ -n "$CRFILE" ] || CRFILE="/etc/honk/custom.rules"
    if [ -s "$CRFILE" ]; then
      sed "s/^/    /" "$CRFILE"
    else
      echo "    # custom rules enabled but $CRFILE is empty"
    fi
  else
    # 白名单之外的 LAN 来源立即直连；保留名单内原有分流规则。
    if [ "$(q control.lan_list_mode)" = "1" ]; then
      allowed="$(q control.lan_proxy | tr ' ' ',')"
      if [ -n "$allowed" ]; then
        echo "    !sip($allowed) -> direct(must)"
      else
        echo "    sip(0.0.0.0/0,::/0) -> direct(must)"
      fi
    fi
    # 只影响"全局"档位：direct 让 v6 整体直连，block_global 让 v6 整体断开。
    # 两者都必须压在最前，否则会被下面的 geosite-cn / geoip-cn 抢先。
    # 回环先放行。resolv.conf 里同时有 127.0.0.1 和 ::1，客户端挑到 ::1 时
    # 如果被下面的 ipversion(6) 规则拦掉，表现是"某些站点解析超时、另一些正常"，
    # 极难查。本机回环永远不该受 v6 策略影响。
    echo "    dip(::1) -> direct(must)"
    case "$IPV6_MODE" in
      direct)       echo "    ipversion(6) -> direct" ;;
      block_global) echo "    ipversion(6) -> block" ;;
    esac
    # 访问控制：源地址优先级最高，压过所有域名规则
    for v in $(uci -q get "$CONF.control.lan_direct"); do
      echo "    sip($v) -> direct"
    done
    for v in $(uci -q get "$CONF.control.lan_proxy"); do
      echo "    sip($v) -> $target"
    done
    for s in $(sections ssid_route); do
      [ "$(uci -q get "$CONF.$s.enabled")" = "1" ] || continue
      src="$(uci -q get "$CONF.$s.source")"
      tgt="$(uci -q get "$CONF.$s.target")"
      [ -n "$src" ] && [ -n "$tgt" ] || continue
      echo "    sip($src) -> $(sq "$tgt")"
    done
    if [ "$ROUTING_MODE" = "bypass_mainland_china" ]; then
      echo "    domain(geosite: geolocation-cn) -> direct"
      echo "    dip(geoip: cn) -> direct"
    fi
    case "$QUIC_MODE" in
      block)  echo "    l4proto(udp) && dport(443) -> block" ;;
      direct) echo "    l4proto(udp) && dport(443) -> direct" ;;
    esac
    # 这一档故意排在 geosite/geoip 之后：CN 的 v6 先被直连规则接住，
    # 只有非 CN 的 v6 落到这里被阻断。想一个不留就用 block_global。
    # 同上：回环必须在 v6 策略之前放行
  [ "$IPV6_MODE" = "block" ] && printf '%s\n' "    dip(::1) -> direct(must)" "    ipversion(6) -> block"

    # 域名分流：一条规则一个 section，domains 是 UCI list
    for s in $(sections domain_route); do
      [ "$(uci -q get "$CONF.$s.enabled")" = "1" ] || continue
      dr_action="$(uci -q get "$CONF.$s.action")"
      [ -n "$dr_action" ] || dr_action="direct"
      dr_args=""
      for d in $(uci -q get "$CONF.$s.domains"); do
        if [ -z "$dr_args" ]; then
          dr_args="suffix: '$(sq "$d")'"
        else
          dr_args="$dr_args, suffix: '$(sq "$d")'"
        fi
      done
      [ -n "$dr_args" ] && echo "    domain($dr_args) -> $(sq "$dr_action")"
    done

    # 目标地址策略：域名规则之后，端口白名单之前
    for v in $(uci -q get "$CONF.control.wan_direct"); do
      echo "    dip($v) -> direct"
    done
    for v in $(uci -q get "$CONF.control.wan_proxy"); do
      echo "    dip($v) -> $target"
    done

    target="direct"
    if [ "$MAIN_GROUP" != "nil" ] && [ -n "$MAIN_GROUP" ]; then
      target="$(sq "$MAIN_GROUP")"
    fi
    if [ "$ROUTING_PORT" = "common" ] && [ "$target" != "direct" ]; then
      # 只代理常用端口，其余直连（等价 passwall2 的 tcp_redir_ports 白名单语义）
      echo "    dport(${COMMON_PORTS}) -> $target"
      echo "    fallback: direct"
    else
      echo "    fallback: $target"
    fi
  fi
  # 不托管 DNS 就把 53 整段交还系统。必须在 dport() 的代理规则之前，
  # must 会终结规则搜索，否则 DNS 仍会被透明代理接走。
  if [ "$DNS_ANY" = "0" ]; then
    echo "    dport(53) -> direct(must)"
  fi
  echo "}"
  echo

  if [ "$DNS_ANY" = "1" ]; then
  echo "dns {"
  [ -n "$DNS_BIND" ] && echo "    bind: '$(sq "$DNS_BIND")'"
  case "$DNS_IPVER" in
    4) echo "    ipversion_prefer: 4" ;;
    6) echo "    ipversion_prefer: 6" ;;
  esac
  [ -n "$DNS_ECS" ] && echo "    client_subnet: '$(sq "$DNS_ECS")'"
  [ -n "$OPT_CACHE" ] && { [ "$OPT_CACHE" = "1" ] && echo "    optimistic_cache: true" || echo "    optimistic_cache: false"; }
  [ -n "$OPT_TTL" ] && echo "    optimistic_cache_ttl: $OPT_TTL"
  [ -n "$STALE_TTL" ] && echo "    optimistic_stale_reply_ttl: $STALE_TTL"
  [ -n "$MAX_CACHE" ] && echo "    max_cache_size: $MAX_CACHE"
  echo "    upstream {"
  cn_up=""
  remote_up=""
  for s in $(sections dns_upstream); do
    [ "$(uci -q get "$CONF.$s.enabled")" = "1" ] || continue
    role="$(q "$s.role")"
    if [ "$role" = "cn" ]; then
      uci -q get "$CONF.infra.cn_dns" >/dev/null 2>&1 && continue
    else
      uci -q get "$CONF.infra.remote_dns" >/dev/null 2>&1 && continue
    fi
    uname="$(uci -q get "$CONF.$s.name")"
    uuri="$(uci -q get "$CONF.$s.uri")"
    uout="$(uci -q get "$CONF.$s.outbound")"
    urole="$(uci -q get "$CONF.$s.role")"
    [ -n "$uname" ] && [ -n "$uuri" ] || continue
    if [ -n "$uout" ]; then
      echo "        $(sq "$uname"): '$(sq "$uuri")' -> $(sq "$uout")"
    else
      echo "        $(sq "$uname"): '$(sq "$uuri")'"
    fi
    # honk 的 dns.routing 一个目标只能指一个上游；多选时取第一个，
    # 其余仍然声明在 upstream 块里（留着备用，不参与路由）。
    case "$urole" in
      cn) [ -z "$cn_up" ] && cn_up="$uname" ;;
      *) [ -z "$remote_up" ] && remote_up="$uname" ;;
    esac
  done

  # 单选字段是唯一的新配置源；旧安装仅在字段不存在时读取旧 section。
  # none 是"明确不设置"的哨兵值：UCI 存不住空串，靠空值表达这个状态会被
  # 当成"字段不存在"，然后回落到旧 dns_upstream，用户看到的就是清空后又自己冒回来。
  case "$CN_DNS" in none) cn_fb="" ;; custom) cn_fb="$CN_DNS_CUSTOM" ;; *) cn_fb="$CN_DNS" ;; esac
  case "$REMOTE_DNS" in none) rm_fb="" ;; custom) rm_fb="$REMOTE_DNS_CUSTOM" ;; *) rm_fb="$REMOTE_DNS" ;; esac
  if [ -n "$cn_fb" ]; then
    echo "        cn_dns: '$(sq "$cn_fb")' -> direct"
    cn_up="cn_dns"
  fi
  if [ -n "$rm_fb" ]; then
    dns_target="$(q config.main_group)"
    [ -n "$dns_target" ] && [ "$dns_target" != "nil" ] || dns_target="direct"
    echo "        remote_dns: '$(sq "$rm_fb")' -> $dns_target"
    remote_up="remote_dns"
  fi

  echo "    }"
  echo "    routing {"
  echo "        request {"
  if [ "$AD_BLOCK" = "1" ]; then
    echo "            qname(geosite: category-ads-all) -> reject"
    # 自定义列表：一行一个域名，按后缀匹配。规则一行不能无限长，
    # 所以按 40 个一组拆成多条。
    if [ -s "$AB_FILE" ]; then
      ab_batch=""
      ab_n=0
      while IFS= read -r ab_d; do
        ab_d="$(printf '%s' "$ab_d" | tr -d '[:space:]')"
        case "$ab_d" in ''|'#'*) continue ;; esac
        if [ -z "$ab_batch" ]; then
          ab_batch="suffix: $ab_d"
        else
          ab_batch="$ab_batch, suffix: $ab_d"
        fi
        ab_n=$((ab_n + 1))
        if [ "$ab_n" -ge 40 ]; then
          echo "            qname($ab_batch) -> reject"
          ab_batch=""
          ab_n=0
        fi
      done < "$AB_FILE"
      [ -n "$ab_batch" ] && echo "            qname($ab_batch) -> reject"
    fi
  fi
  [ "$BLOCK_HTTPS" = "1" ] && echo "            qtype(https,svcb) -> reject"
  for s in $(sections ssid_route); do
    [ "$(uci -q get "$CONF.$s.enabled")" = "1" ] || continue
    src="$(uci -q get "$CONF.$s.source")"
    dnsserver="$(uci -q get "$CONF.$s.dns")"
    [ -n "$src" ] && [ -n "$dnsserver" ] || continue
    case "$dnsserver" in
      cn|cn_dns|cn_*) dnsserver="$cn_up" ;;
      remote|remote_dns|remote_*) dnsserver="$remote_up" ;;
    esac
    [ -n "$dnsserver" ] && echo "            sip($src) -> $(sq "$dnsserver")"
  done
  if [ "$ROUTING_MODE" = "bypass_mainland_china" ] && [ -n "$cn_up" ]; then
    echo "            qname(geosite: geolocation-cn) -> $(sq "$cn_up")"
  fi
  fb="$remote_up"
  [ -n "$fb" ] || fb="$cn_up"
  if [ -n "$fb" ]; then
    echo "            fallback: $(sq "$fb")"
  else
    echo "            fallback: reject"
  fi
  echo "        }"
  echo "    }"
  echo "}"
  fi

  # experimental 下可能同时要 cache_file 和 native_api，
  # 必须攒到一起写，不能各写一个 experimental 块（重复块后者会覆盖前者）。
  exp_inner=""
  if [ "$CACHE_FILE" = "1" ]; then
    exp_inner="${exp_inner}    cache_file {
        enabled: true
        store_dns: true
    }
"
  fi
  if [ "$NATIVE_API" = "1" ]; then
    # 只监听回环 + 匿名访问，不开 config_write：够看延迟和切节点，
    # 不给 UI 改配置的权限。
    # enabled 默认 false，不写这一行监听器根本不会启动（只写 listen 无效）。
    api_inner="        enabled: true
        listen: '127.0.0.1:${API_PORT}'
        allow_anonymous_loopback: true
"
    # doona 装了就把 ui 指过去；ui 只接受含 index.html 的本地目录。
    if [ -f /usr/share/doona/index.html ]; then
        api_inner="${api_inner}        ui: '/usr/share/doona'
"
    fi
    exp_inner="${exp_inner}    native_api {
${api_inner}    }
"
  fi
  if [ -n "$exp_inner" ]; then
    echo
    echo "experimental {"
    printf '%s' "$exp_inner"
    echo "}"
  fi

} > "$TMP"

mv "$TMP" "$OUT"